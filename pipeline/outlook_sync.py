def _get_outlook():
    """Return (outlook_app, namespace) COM objects."""
    try:
        import win32com.client
    except ImportError:
        print("\n" + "="*60)
        print("  MISSING DEPENDENCY: pywin32")
        print("="*60)
        print("  Run this once in your terminal (as Administrator if needed):")
        print("    pip install pywin32")
        print("="*60)
        sys.exit(1)

    try:
        outlook = win32com.client.Dispatch("Outlook.Application")
        ns = outlook.GetNamespace("MAPI")
        return outlook, ns
    except Exception as e:
        print(f"\n  ERROR: Could not connect to Outlook: {e}")
        print("  Make sure Outlook is installed and signed in.")
        sys.exit(1)


def _walk_folders(folder, path=""):
    """Recursively yield (folder, full_path) for every MAPI folder."""
    try:
        name = folder.Name
    except Exception:
        return
    full = f"{path} / {name}" if path else name
    yield folder, full
    try:
        for sub in folder.Folders:
            yield from _walk_folders(sub, full)
    except Exception:
        pass


def _all_calendar_folders(ns):
    """
    Yield (folder, label) for every folder that looks like a calendar
    across ALL stores — including subscribed/shared/internet calendars.
    """
    seen = set()
    for store in ns.Stores:
        try:
            root = store.GetRootFolder()
        except Exception:
            continue
        for folder, path in _walk_folders(root):
            try:
                fid = folder.EntryID
            except Exception:
                continue
            if fid in seen:
                continue
            seen.add(fid)
            try:
                # DefaultItemType 1 = olAppointmentItem (calendar)
                if folder.DefaultItemType == 1:
                    yield folder, path
            except Exception:
                pass
    # Also try the MAPI default calendar in case it wasn't found above
    try:
        cal = ns.GetDefaultFolder(_OL_FOLDER_CALENDAR)
        fid = cal.EntryID
        if fid not in seen:
            seen.add(fid)
            yield cal, "Default Calendar"
    except Exception:
        pass


def _get_hbs_calendar(ns):
    """
    Return the calendar folder most likely to contain HBS class events.
    Checks all calendars for one that contains items with course keywords,
    then falls back to the largest HBS/harvard-labeled calendar.
    """
    course_keywords = [k.lower() for k in COURSES.keys()]  # bgie, fin2, lca, etc.
    all_cals = list(_all_calendar_folders(ns))

    # First pass: find any calendar that has items matching course abbreviations
    for cal, label in all_cals:
        try:
            items = cal.Items
            items.IncludeRecurrences = True
            items.Sort("[Start]")
            count = 0
            for item in items:
                try:
                    subj = (item.Subject or "").lower()
                    if any(k in subj for k in course_keywords):
                        return cal, label   # found it — has HBS class events
                    count += 1
                    if count > 100:        # only scan first 100 items
                        break
                except Exception:
                    continue
        except Exception:
            continue

    # Second pass: prefer HBS/harvard-labeled store
    for cal, label in all_cals:
        if any(k in label.lower() for k in ("hbs", "harvard", "section")):
            return cal, label

    # Fall back to default calendar
    try:
        cal = ns.GetDefaultFolder(_OL_FOLDER_CALENDAR)
        return cal, "Default Calendar"
    except Exception:
        pass

    if all_cals:
        return all_cals[0]
    raise RuntimeError("No calendar folders found in Outlook.")


